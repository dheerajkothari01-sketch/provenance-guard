"""
Build PROOF_PACK.md from a real engine run, so every number in it is reproducible.

    python tools/build_proof_pack.py [evidence_folder]      (default: data/sample)
"""
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from engine.guard import RULES, Settings, evaluate, load_folder, metrics  # noqa: E402

folder = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "sample"
s = Settings()
data = load_folder(folder)
dec, clocks = evaluate(data, s)
m = metrics(dec, data.get("LABELS"))
bank = dec[dec["is_bank"]]
is_test = data.get("LABELS") is not None
try:
    commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"], capture_output=True,
                            text=True).stdout.strip() or "n/a"
except OSError:
    commit = "n/a"

L = []
add = L.append
add("# Proof Pack: Payment-Run Provenance Guard")
add("")
add("CRIMEATHON'26 · Case CR-26-047 · Defense track · Team Brute Force (Dheeraj, Ashwantika, Mahashri, Jazib)")
add("")
add(f"Generated {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from a live engine run · code version `{commit}` · "
    f"data folder `{folder.relative_to(ROOT) if folder.is_relative_to(ROOT) else folder}`")
add("")
if is_test:
    add("> **Data used.** The official evidence package (E01–E20 log files) was not available to our team when this "
        "pack was built: we received only the case file describing it. Every result below is on our **synthetic test "
        "dataset**, generated by `tools/make_sample_data.py` in the exact column formats of Appendix D, with planted "
        "attacks and labelled ground truth. These are **not findings from the case evidence**. The same command "
        "runs unchanged on the supplied files (section 1).")
    add("")

add("## 1. How to reproduce")
add("")
add("Requires Python 3.10+.")
add("")
add("```bash")
add("git clone <repository-url> && cd provenance-guard")
add("pip install -r requirements.txt")
add("")
add("# 1. regenerate the test dataset (deterministic, seed 47)")
add("python tools/make_sample_data.py data/sample")
add("")
add("# 2. run the engine (no dashboard) and write decisions.csv + report.md")
add("python run_guard.py data/sample --out output")
add("")
add("# 3. on the supplied evidence: put the files in one folder, named by evidence ID, then")
add("python run_guard.py path/to/evidence --out output")
add("")
add("# 4. rebuild this proof pack from a fresh run")
add("python tools/build_proof_pack.py data/sample")
add("")
add("# 5. dashboard with sign-in, hold queue and audit trail")
add("streamlit run app.py")
add("```")
add("")
add("Expected command-line output on the test data ends with:")
add("")
if m:
    add(f"`TEST accuracy: {m['fraud_held']}/{m['frauds']} attacks held ({m['detection_rate']}%), "
        f"{m['fraud_review']} sent to review, {m['fraud_missed']} missed; false alarms (normal changes held): "
        f"{m['benign_held']}/{m['benign']}`")
add("")

add("## 2. Required input files and formats")
add("")
add("Files are recognised by **name prefix** (e.g. `E19_anything.csv`). Only E19 is required; each extra file adds a "
    "link to the provenance chain.")
add("")
add("| File | Format | Columns used | Time basis | Used for |")
add("| --- | --- | --- | --- | --- |")
add("| **E19** vendor record change log | CSV | ts_utc, change_id, vendor_id, vendor_name, field, old_value, new_value, "
    "changed_by, channel, approval_ref, source_ip, request_id | UTC | **Required.** The changes being judged |")
add("| E18 / E01 LedgerOne API log | CSV | ts_utc, request_id, api_key_id, caller_ip, user_agent, endpoint, method | "
    "UTC | Links a change to its key, IP and client via request_id; learns each key's normal network |")
add("| E04 connected software register | JSON | credential_id, integration, scope, ip_restriction, last_review, status "
    "| — | Key permissions, IP restriction, review age, disabled keys |")
add("| E03 single sign-on log | CSV | ts_utc, user, source_ip, city, mfa_result, device_id, result | UTC | How a staff "
    "member signed in before a change |")
add("| E15 private-link flow log | CSV | ts_utc, src_ip, src_label, tunnel_id | UTC | Corroboration only (labels "
    "supplied by the outside company) |")
add("| E17 indicator list | CSV | indicator, type, confidence | — | Outside company's indicators (unverified) |")
add("| E02 HelpDeskr audit log | CSV | ts_local | Tenant local, assumed IST (−330 min) | Clock handling only |")
add("| E05 BlueVault log | CSV | epoch_s | Unsynchronised: offset set by hand | Clock handling only |")
add("| labels_*.csv | CSV | change_id, label, scenario | — | **Test data only**: ground truth for accuracy |")
add("")
add("Clock conversion applied in this run:")
add("")
add("| File | Column | Basis | Minutes added | Rows |")
add("| --- | --- | --- | --- | --- |")
for _, c in clocks.iterrows():
    add(f"| {c['file']} | {c['column']} | {c['basis']} | {c['minutes_added']} | {c['rows']} |")
add("")

add("## 3. Detection rules")
add("")
add("Scored on bank-detail changes only (bank account, IFSC, IBAN, SWIFT, beneficiary, payee). Points add up, "
    f"capped at 100. **HOLD at ≥ {s.hold_threshold}, REVIEW at ≥ {s.review_threshold}, else ALLOW.** "
    "The largest single rule is 40, so at least two independent signals must agree before money is held.")
add("")
add("| Rule | Points |")
add("| --- | --- |")
for k, (desc, w) in RULES.items():
    add(f"| {desc} | {w} |")
add("")

add("## 4. Results")
add("")
c = bank["decision"].value_counts()
add(f"Rows read: " + ", ".join(f"{k} {len(v)}" for k, v in sorted(data.items())) + ".")
add("")
add(f"**{len(dec)} vendor changes**, of which **{len(bank)} bank-detail changes** were scored: "
    f"HOLD {int(c.get('HOLD', 0))}, REVIEW {int(c.get('REVIEW', 0))}, ALLOW {int(c.get('ALLOW', 0))}.")
add("")
if m:
    add("| Measure | Result |")
    add("| --- | --- |")
    add(f"| Attacks held | **{m['fraud_held']} / {m['frauds']}** ({m['detection_rate']}%) |")
    add(f"| Attacks held or sent to review | **{m['fraud_held'] + m['fraud_review']} / {m['frauds']}** "
        f"({m['flagged_rate']}%) |")
    add(f"| Attacks missed (allowed) | {m['fraud_missed']} |")
    add(f"| Normal bank changes held (false alarms) | **{m['benign_held']} / {m['benign']}** "
        f"({m['false_alarm_rate']}%) |")
    add(f"| Normal bank changes sent to review | {m['benign_review']} / {m['benign']} |")
    add("")
    t = m["table"]
    add("### Every attack")
    add("")
    add("| Change | Scenario | Decision | Score | Why |")
    add("| --- | --- | --- | --- | --- |")
    for _, r in t[t["label"] == "fraud"].sort_values("score", ascending=False).iterrows():
        add(f"| {r.change_id} | {r.scenario} | **{r.decision}** | {r.score} | {r.reasons.replace(' | ', '; ')} |")
    add("")

add("## 5. Errors: missed detections, false positives, false alarms")
add("")
if m:
    t = m["table"]
    miss = t[(t["label"] == "fraud") & (t["decision"] != "HOLD")]
    add(f"**Attacks not held ({len(miss)})**: none were allowed; each went to REVIEW for a person:")
    add("")
    for _, r in miss.iterrows():
        add(f"- **{r.change_id}** ({r.scenario}): score {r.score}, {r.decision}. {r.reasons.replace(' | ', '; ')}")
    add("")
    fp = t[(t["label"] != "fraud") & (t["decision"] != "ALLOW")]
    add(f"**Normal changes flagged ({len(fp)})**: none were held; all went to REVIEW:")
    add("")
    for _, r in fp.iterrows():
        add(f"- **{r.change_id}** ({r.scenario}): score {r.score}, {r.decision}. {r.reasons.replace(' | ', '; ')}")
    add("")
    add("The two unapproved staff edits broke the approval process, so a REVIEW is the intended result, not an error. "
        "The travelling manager is a genuine false positive at REVIEW level.")
    add("")
    tricky = t[t["scenario"].str.startswith("tricky")]
    add("**Tricky normal events built to provoke false alarms**: decisions:")
    add("")
    for _, r in tricky.iterrows():
        add(f"- {r.change_id} ({r.scenario.replace('tricky normal: ', '')}): **{r.decision}**, score {r.score}")
    add("")

add("## 6. Evidence IDs supporting the findings")
add("")
add("| Evidence | Role in our conclusions |")
add("| --- | --- |")
add("| **E19** vendor change log | The bank-detail change with no approval reference: the core of the problem |")
add("| **E18 / E01** API logs | request_id links each change to the key, IP and client that made it |")
add("| **E17** indicator list (with **E16** notice) | Outside company's attacker indicators; used as one signal, never alone |")
add("| **E04** software register | TallyBridge key: vendors:write scope, no IP restriction, no review since Jun 2024 |")
add("| **E15** private-link flows | Shows whether a request came over TallyBridge's private link (corroboration) |")
add("| **E03** SSO log, **E14** roster | Rule out the ex-employee and the travelling contractor; check staff sign-ins |")
add("| **E02 + E06** | Extra HelpDeskr export jobs and the billing alert: data theft before the bank change |")
add("| **E05** BlueVault log | Access to finance statements and bank instructions (clock offset noted) |")
add("| **E07** onboarding review | TallyBridge approved on self-reported answers |")
add("| **E08** contract | Breach-notification duty (notice on 21 Aug was vague) |")
add("| **E09, E10, E11** | Risk known and not acted on; policy (annual review, approvals) not followed; audit findings open |")
add("")

add("## 7. Known limitations")
add("")
add("- **Forged approval references** are not checked against an approval register (none supplied). A forged "
    "reference from the expected network scores low and is sent to REVIEW, not HOLD (chg in section 5).")
add("- **Stolen staff login with a forged approval** reaches REVIEW (35), not HOLD; it relies on E03 showing a new "
    "device, new city, MFA problem or failed attempts.")
add("- **Business-email compromise** where a deceived manager approves the change scores REVIEW; the protection is "
    "the call-back to the phone number on file *before* any recent change, which the app displays.")
add("- **Learned networks can be poisoned** by an attacker who sends more than 5% of a key's traffic from a new range "
    "(about 65 calls for TallyBridge's key in this data).")
add("- **Weights are expert-set**, not statistically fitted. With few labelled cases, rates have wide uncertainty.")
add("- **Test data is ours.** Variations were designed to dodge simple rules, but real validation needs the supplied "
    "evidence or labelled history.")
add("- **Log quality:** LedgerOne keeps API logs for 90 days; BlueVault's clock is unsynchronised; E15 labels and "
    "E17 indicators come from the breached party and are unverified.")
add("- **Scope:** vendor bank-detail changes only. Data theft through exports (E02) is detected by the case "
    "evidence, not by this tool.")
add("- **Demo-grade sign-in:** salted PBKDF2 hashes, no lockout; audit log is append-only but not tamper-proof. "
    "Production would use company SSO with MFA and tamper-evident logging.")
add("")
out = ROOT / "PROOF_PACK.md"
out.write_text("\n".join(L) + "\n")
print(f"wrote {out}")
